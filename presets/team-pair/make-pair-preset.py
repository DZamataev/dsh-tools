#!/usr/bin/env python3
"""Generate the operator `pair` override of the Agent Teams bundle's `preset-team` row.

The bundle (packages/experimental/agent-team-profile/cordis.patch.yml) ships `preset-team`:
the standard preset with subagent delegation replaced by `tool-agent-team`. A loader patch
cannot reach the nested `tool-agent-team` row, so this script copies the bundle's complete
preset config, injects the operator's models/roles into that nested row, renames the preset,
and writes a top-level `- id: preset-team` patch (config replaces the row's config wholesale).

Usage: make-pair-preset.py <bundle cordis.patch.yml> <roles yaml> <out yml>
The roles file holds the `models:` and `roles:` mappings at indentation 0.
"""
import re
import sys

bundle_path, roles_path, out_path = sys.argv[1:4]
lines = open(bundle_path, encoding='utf-8').read().splitlines()

start = next(i for i, l in enumerate(lines) if re.match(r'^\s*- id: preset-team\s*$', l))
row_indent = len(lines[start]) - len(lines[start].lstrip())
end = len(lines)
for j in range(start + 1, len(lines)):
    l = lines[j]
    if l.strip() and (len(l) - len(l.lstrip())) <= row_indent:
        end = j
        break
row = lines[start:end]
while row and not row[-1].strip():
    row.pop()

cfg = next(i for i, l in enumerate(row) if re.match(r'^\s*config:\s*$', l))
cfg_indent = len(row[cfg]) - len(row[cfg].lstrip())
body = row[cfg + 1:]

# rename the preset shown in the picker
name_line = next(i for i, l in enumerate(body) if re.match(r'^\s*name: Agent Teams\s*$', l))
body[name_line] = re.sub(r'name: .*$', 'name: "Team mode"', body[name_line])
desc_line = next(i for i, l in enumerate(body) if re.match(r'^\s*description: ', l))
body[desc_line] = re.sub(r'description: .*$', 'description: "Standard mode plus Agent Teams: you lead, and can add a GPT coder or reviewer (they run in Codex teammate mode) and a Claude reviewer. Teammates replace subagent delegation."', body[desc_line])

# replace the nested tool-agent-team config
tat = next(i for i, l in enumerate(body) if re.match(r'^\s*- id: tool-agent-team\s*$', l))
item_indent = len(body[tat]) - len(body[tat].lstrip())
tcfg = next(i for i in range(tat + 1, len(body)) if re.match(r'^\s*config:\s*$', body[i]))
tcfg_indent = len(body[tcfg]) - len(body[tcfg].lstrip())
tend = len(body)
for k in range(tcfg + 1, len(body)):
    l = body[k]
    if l.strip() and (len(l) - len(l.lstrip())) <= item_indent:
        tend = k
        break
roles = [l for l in open(roles_path, encoding='utf-8').read().splitlines()]
pad = ' ' * (tcfg_indent + 2)
new_cfg = [pad + 'freshProvider: spawn', pad + 'forkProvider: fork'] + [(pad + l) if l.strip() else '' for l in roles]
body = body[:tcfg + 1] + new_cfg + body[tend:]

dedent = cfg_indent - 2
out = [
    '# Generated by dsh-tools presets/team-pair/make-pair-preset.py from the Agent Teams bundle.',
    '# Overrides the bundle `team` preset: same tools, operator models/roles, picker name "Team mode".',
    '- id: preset-team',
    '  config:',
] + [l[dedent:] if l.strip() else '' for l in body]
open(out_path, 'w', encoding='utf-8').write('\n'.join(out) + '\n')
print(f'wrote {out_path} ({len(out)} lines)')
